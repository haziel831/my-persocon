// Exposes the host API (Tauri commands/events) to the rest of the renderer.
const { invoke } = window.__TAURI__.core;
const { listen } = window.__TAURI__.event;

window.petAPI = {
  getConfig: () => invoke('get_config'),
  saveConfig: (patch) => invoke('save_config', { patch }),
  loadModel: () => invoke('load_model'),
  loadModelDir: (dir) => invoke('load_model_dir', { dir }),
  installSideModel: ({ path, name, texture }) => invoke('install_side_model', { path, name, texture }),
  loadSave: (demo = false) => invoke('load_save', { demo }),
  storeSave: (data) => invoke('store_save', { data }),
  exportSave: () => invoke('export_save'),
  importSave: () => invoke('import_save'),
  resetSave: () => invoke('reset_save'),
  getAutostart: () => invoke('get_autostart'),
  setAutostart: (value) => invoke('set_autostart', { value }),
  makeReport: (info) => invoke('make_report', { info }),
  pickModelSource: (folder) => invoke('pick_model_source', { folder }),
  inspectModel: (path) => invoke('inspect_model', { path }),
  importModel: ({ path, name, texture, petHeight }) => invoke('import_model', { path, name, texture, petHeight }),
  setInteractive: (value) => invoke('set_interactive', { value }),
  passClick: () => invoke('pass_click'),
  setStreamer: (value) => invoke('set_streamer', { value }),
  onStreamer: (cb) => listen('streamer', (e) => cb(!!e.payload)),
  onClickThrough: (cb) => listen('click-through', () => cb()),
  onTrayClick: (cb) => listen('tray_click', () => cb()),
  desktopIcons: () => invoke('desktop_icons'),
  openDesktopItem: (path) => invoke('open_desktop_item', { path }),
  desktopAll: () => invoke('desktop_all'),
  moveIcon: (name, dx, dy) => invoke('move_icon', { name, dx, dy }),
  placeIcon: (name, x, y) => invoke('place_icon', { name, x, y }),
  setCursor: (x, y) => invoke('set_cursor', { x, y }),
  inputState: () => invoke('input_state'),
  focusWindow: () => invoke('focus_window'),
  clipboardText: () => invoke('clipboard_text'),
  setAlwaysOnTop: (value) => invoke('set_on_top', { value }),
  watchKeys: (value) => invoke('watch_keys', { value }),
  quit: () => invoke('quit'),
  onWorld: (cb) => listen('world', (e) => cb(e.payload)),
  // Tauri 2 intercepts OS file drops and delivers local paths through these events.
  onFileDrop: (cb) => listen('tauri://drag-drop', (e) => cb(e.payload)),
  onFileDropHover: (cb) => listen('tauri://drag-enter', (e) => cb(e.payload)),
  onFileDropOver: (cb) => listen('tauri://drag-over', (e) => cb(e.payload)),
  onFileDropCancel: (cb) => listen('tauri://drag-leave', () => cb()),
  setDisplay: (index) => invoke('set_display', { index }),
  audioListen: (value) => invoke('audio_listen', { value }),
  onAudio: (cb) => listen('audio', (e) => cb(e.payload)),
  savePreview: (name, dataUrl) => invoke('save_preview', { name, dataUrl }),
  previewDone: () => invoke('preview_done'),
  setTrayIcon: (dataUrl) => invoke('set_tray_icon', { dataUrl }),
  pickFile: (title, label, exts) => invoke('pick_file', { title, label, exts }),
  readFileData: (path) => invoke('read_file_data', { path }),
  fetchMidi: (url) => invoke('fetch_midi', { url }),
  readZip: (path, prefixes, maxFiles = 4000) => invoke('read_zip', { path, prefixes, maxFiles }),
  storeBlob: (name, data) => invoke('store_blob', { name, data }),
  loadBlob: (name) => invoke('load_blob', { name }),
  importMcSkin: ({ name, skin, slim, petHeight }) => invoke('import_mc_skin', { name, skin, slim, petHeight }),
  listModels: () => invoke('list_models'),
  deleteModel: (dir) => invoke('delete_model', { dir }),
  log: (...args) => invoke('log', { msg: args.map(String).join(' ') }),
  logLines: (lines) => invoke('log_lines', { lines }),
  getVersion: () => window.__TAURI__.app?.getVersion() ?? Promise.resolve(''),
};
